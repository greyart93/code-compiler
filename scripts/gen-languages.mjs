// Generates src/data/<lang>.ts for the remaining languages.
//
// The lesson bodies live here as structured data (with real newlines) rather
// than as escaped TypeScript string literals, which is what made hand-editing
// these files error-prone. Run: node scripts/gen-languages.mjs

import fs from "node:fs";

/** wrap every string in double quotes, escaping what TS needs */
const q = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';

const code = (lang, body) => "```" + lang + "\n" + body + "\n```";

/** an exercise: { type, ... } kept as plain data */
const ex = (e) => {
  const parts = [`type: ${q(e.type)}`];
  if (e.prompt) parts.push(`prompt: ${q(e.prompt)}`);
  if (e.problem) parts.push(`problem: ${q(e.problem)}`);
  if (e.starterCode) parts.push(`starterCode: ${q(e.starterCode)}`);
  if (e.expectedOutput) parts.push(`expectedOutput: ${q(e.expectedOutput)}`);
  if (e.answerLabel) parts.push(`answerLabel: ${q(e.answerLabel)}`);
  if (e.template) parts.push(`template: ${q(e.template)}`);
  if (e.answers) parts.push(`answers: [${e.answers.map(q).join(", ")}]`);
  if (e.snippet) parts.push(`snippet: ${q(e.snippet)}`);
  if (e.placeholder) parts.push(`placeholder: ${q(e.placeholder)}`);
  if (e.hint) parts.push(`hint: ${q(e.hint)}`);
  if (e.explanation) parts.push(`explanation: ${q(e.explanation)}`);
  if (e.blanks)
    parts.push(
      `blanks: [${e.blanks
        .map((b) => `{ options: [${b.options.map(q).join(", ")}], answer: ${q(b.answer)} }`)
        .join(", ")}]`
    );
  if (e.tests)
    parts.push(
      `tests: [${e.tests
        .map(
          (t) =>
            `{ input: ${q(t.input)}, expected: ${q(t.expected)}, label: ${q(t.label)} }`
        )
        .join(", ")}]`
    );
  return `{ ${parts.join(", ")} }`;
};

function renderLesson(l, lang, fence) {
  const lines = [];
  lines.push("    {");
  lines.push(`      id: ${q(l.id)},`);
  lines.push(`      title: ${q(l.title)},`);
  lines.push(`      minutes: ${l.minutes},`);
  lines.push("      md: [");
  for (const part of l.md) {
    lines.push(`        ${q(typeof part === "string" ? part : fence(part))},`);
  }
  lines.push('      ].join("\\n"),');
  const list = l.exercises || (l.exercise ? [l.exercise] : []);
  if (list.length) {
    lines.push("      exercises: [");
    for (const e of list) lines.push(`        ${ex(e)},`);
    lines.push("      ],");
  }
  lines.push("    },");
  return lines.join("\n");
}

function renderSection(s, lang, fence) {
  return [
    "export const " + s.const + ": SectionSeed = {",
    `  id: ${q(s.id)},`,
    `  title: ${q(s.title)},`,
    "  lessons: [",
    s.lessons.map((l) => renderLesson(l, lang, fence)).join("\n"),
    "  ],",
    "};",
  ].join("\n");
}

function renderFile(lang, fenceLang, sections) {
  const constName = lang.toUpperCase().replace(/[^A-Z]/g, "_");
  const fence = (body) => code(fenceLang, body);
  const head = [
    `// ${constName} course content — generated by scripts/gen-languages.mjs.`,
    "// Edit the data in that script, then re-run it; do not edit this file by hand.",
    'import type { SectionSeed } from "./course-types";',
    "",
  ].join("\n");
  const body = sections.map((s) => renderSection(s, lang, fence)).join("\n\n");
  fs.writeFileSync(`src/data/${lang}.ts`, head + "\n" + body + "\n", "utf8");
  const n = sections.reduce((a, s) => a + s.lessons.length, 0);
  console.log(`wrote src/data/${lang}.ts — ${sections.length} sections, ${n} lessons`);
}

export { renderFile, q, ex, code };

if (import.meta.url.endsWith(process.argv[1].replace(/\\/g, "/"))) {
  const A = await import("./langs-ts-go-rust.mjs");
  const B = await import("./langs-others.mjs");
  const LANGS = [
    ["typescript", "typescript", A.TS_SECTIONS],
    ["go", "go", A.GO_SECTIONS],
    ["rust", "rust", A.RUST_SECTIONS],
    ["php", "php", B.PHP_SECTIONS],
    ["csharp", "csharp", B.CS_SECTIONS],
    ["kotlin", "kotlin", B.KT_SECTIONS],
    ["dart", "dart", B.DART_SECTIONS],
    ["swift", "swift", B.SWIFT_SECTIONS],
    ["ruby", "ruby", B.RB_SECTIONS],
    ["lua", "lua", B.LUA_SECTIONS],
    ["bash", "bash", B.BASH_SECTIONS],
    ["assembly", "nasm", B.ASM_SECTIONS],
  ];
  for (const [lang, fenceLang, sections] of LANGS) renderFile(lang, fenceLang, sections);
}